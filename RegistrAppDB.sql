-- =========================================================================
-- CREACIÓN DE TABLAS (ORDEN DE DEPENDENCIAS)
-- =========================================================================

-- 1. Tabla ROL (Sin dependencias)
CREATE TABLE ROL (
    id_rol INT GENERATED BY DEFAULT AS IDENTITY,
    nombre_rol VARCHAR(50) NOT NULL,
    CONSTRAINT PK_ROL PRIMARY KEY (id_rol),
    CONSTRAINT UQ_NOMBRE_ROL UNIQUE (nombre_rol)
);

-- 2. Tabla USUARIO (Depende de ROL)
CREATE TABLE USUARIO (
    id_usuario INT GENERATED BY DEFAULT AS IDENTITY,
    id_rol INT NOT NULL,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    estado VARCHAR(20) DEFAULT 'Activo' NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (id_usuario),
    CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (id_rol) REFERENCES ROL(id_rol) ON DELETE RESTRICT,
    CONSTRAINT UQ_USUARIO_EMAIL UNIQUE (email)
);

-- 3. Tabla AUDITORIA (Depende de USUARIO)
CREATE TABLE AUDITORIA (
    id_log BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario INT NOT NULL,
    fecha_intento TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    accion VARCHAR(255) NOT NULL,
    ip_origen VARCHAR(45) NOT NULL, -- Soporta IPv4 e IPv6
    CONSTRAINT PK_AUDITORIA PRIMARY KEY (id_log),
    CONSTRAINT FK_AUDITORIA_USUARIO FOREIGN KEY (id_usuario) REFERENCES USUARIO(id_usuario) ON DELETE CASCADE
);

-- 4. Tabla CATEGORIA (Sin dependencias)
CREATE TABLE CATEGORIA (
    id_categoria INT GENERATED BY DEFAULT AS IDENTITY,
    nombre_categoria VARCHAR(100) NOT NULL,
    CONSTRAINT PK_CATEGORIA PRIMARY KEY (id_categoria),
    CONSTRAINT UQ_NOMBRE_CATEGORIA UNIQUE (nombre_categoria)
);

-- 5. Tabla PRODUCTO (Depende de CATEGORIA)
CREATE TABLE PRODUCTO (
    id_producto INT GENERATED BY DEFAULT AS IDENTITY,
    id_categoria INT NOT NULL,
    nombre_producto VARCHAR(150) NOT NULL,
    precio_compra NUMERIC(12, 2) NOT NULL,
    precio_venta NUMERIC(12, 2) NOT NULL,
    stock_actual INT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PRODUCTO PRIMARY KEY (id_producto),
    CONSTRAINT FK_PRODUCTO_CATEGORIA FOREIGN KEY (id_categoria) REFERENCES CATEGORIA(id_categoria) ON DELETE RESTRICT,
    CONSTRAINT CHK_STOCK_MINIMO CHECK (stock_actual >= 0)
);

-- 6. Tabla FACTURA (Depende de USUARIO)
CREATE TABLE FACTURA (
    id_factura BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario INT NOT NULL,
    fecha_emision TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    total_factura NUMERIC(12, 2) DEFAULT 0.00 NOT NULL,
    CONSTRAINT PK_FACTURA PRIMARY KEY (id_factura),
    CONSTRAINT FK_FACTURA_USUARIO FOREIGN KEY (id_usuario) REFERENCES USUARIO(id_usuario) ON DELETE RESTRICT
);

-- 7. Tabla FACTURA_PRODUCTO (Resolución M:N - Depende de FACTURA y PRODUCTO)
CREATE TABLE FACTURA_PRODUCTO (
    id_factura BIGINT NOT NULL,
    id_producto INT NOT NULL,
    cantidad INT NOT NULL,
    precio_unitario NUMERIC(12, 2) NOT NULL,
    CONSTRAINT PK_FACTURA_PRODUCTO PRIMARY KEY (id_factura, id_producto),
    CONSTRAINT FK_DETALLE_FACTURA FOREIGN KEY (id_factura) REFERENCES FACTURA(id_factura) ON DELETE CASCADE,
    CONSTRAINT FK_DETALLE_PRODUCTO FOREIGN KEY (id_producto) REFERENCES PRODUCTO(id_producto) ON DELETE RESTRICT,
    CONSTRAINT CHK_CANTIDAD_POSITIVA CHECK (cantidad > 0)
);

-- =========================================================================
-- CREACIÓN DE ÍNDICES OPTIMIZADOS PARA RENDIMIENTO
-- =========================================================================
CREATE INDEX IX_USUARIO_ROL ON USUARIO(id_rol);
CREATE INDEX IX_PRODUCTO_CATEGORIA ON PRODUCTO(id_categoria);
CREATE INDEX IX_FACTURA_USUARIO ON FACTURA(id_usuario);
CREATE INDEX IX_AUDITORIA_FECHA ON AUDITORIA(fecha_intento);
